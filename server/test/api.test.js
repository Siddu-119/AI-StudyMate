import assert from "node:assert/strict";
import { after, before, test } from "node:test";

process.env.AI_DEMO_MODE = "true";

const { app, classifyProviderError, startServer } = await import("../index.js");
let server;
let baseUrl;

before(async () => {
  server = app.listen(0, "127.0.0.1");
  await new Promise((resolve, reject) => {
    server.once("listening", resolve);
    server.once("error", reject);
  });
  baseUrl = `http://127.0.0.1:${server.address().port}`;
});

after(async () => {
  if (server?.listening) {
    await new Promise((resolve, reject) => server.close((error) => (error ? reject(error) : resolve())));
  }
});

async function jsonRequest(path, options) {
  const response = await fetch(`${baseUrl}${path}`, options);
  return { response, body: await response.json() };
}

test("health and AI status identify explicitly enabled demo mode", async () => {
  const health = await jsonRequest("/api/health");
  const status = await jsonRequest("/api/ai/status");

  assert.equal(health.response.status, 200);
  assert.equal(health.body.ok, true);
  assert.equal(health.body.mode, "demo");
  assert.equal(status.body.mode, "demo");
  assert.equal(status.body.provider, "Google Gemini");
  assert.match(status.body.message, /not generated by an AI model/);
  assert.equal(JSON.stringify(status.body).includes("GEMINI_API_KEY"), false);
});

test("CORS allows the local client origin and does not reflect an unknown origin", async () => {
  const allowed = await fetch(`${baseUrl}/api/health`, {
    headers: { Origin: "http://localhost:5173" },
  });
  const denied = await fetch(`${baseUrl}/api/health`, {
    headers: { Origin: "https://untrusted.example" },
  });

  assert.equal(allowed.headers.get("access-control-allow-origin"), "http://localhost:5173");
  assert.equal(denied.headers.get("access-control-allow-origin"), null);
});

test("explanation validates empty topics and returns labelled sample content", async () => {
  const invalid = await jsonRequest("/api/ai/explain", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ topic: "   " }),
  });
  assert.equal(invalid.response.status, 400);

  const explanation = await jsonRequest("/api/ai/explain", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ subject: "Physics", topic: "Ohm's Law", difficulty: "beginner" }),
  });
  assert.equal(explanation.response.status, 200);
  assert.equal(explanation.body.mode, "demo");
  assert.match(explanation.body.explanation, /V = I × R/);
  assert.match(explanation.body.explanation, /volts/i);
});

test("quiz generation respects the requested count and response shape", async () => {
  const quiz = await jsonRequest("/api/ai/quiz", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ subject: "Physics", topic: "Ohm's Law", count: 5 }),
  });

  assert.equal(quiz.response.status, 200);
  assert.equal(quiz.body.mode, "demo");
  assert.equal(quiz.body.questions.length, 5);
  for (const question of quiz.body.questions) {
    assert.equal(question.options.length, 4);
    assert.ok(question.correctIndex >= 0 && question.correctIndex <= 3);
    assert.ok(question.explanation.length > 0);
  }
});

test("follow-up requests return labelled demo answers and validate empty questions", async () => {
  const invalid = await jsonRequest("/api/ai/follow-up", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ question: " " }),
  });
  assert.equal(invalid.response.status, 400);

  const followUp = await jsonRequest("/api/ai/follow-up", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      subject: "Physics",
      topic: "Ohm's Law",
      question: "What happens if resistance doubles?",
    }),
  });
  assert.equal(followUp.response.status, 200);
  assert.equal(followUp.body.mode, "demo");
  assert.match(followUp.body.answer, /half|decreas/i);
});

test("unknown routes and malformed JSON return client errors", async () => {
  const missing = await jsonRequest("/api/not-found");
  assert.equal(missing.response.status, 404);

  const malformed = await jsonRequest("/api/ai/explain", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: "{",
  });
  assert.equal(malformed.response.status, 400);
  assert.match(malformed.body.error, /invalid JSON/i);
});

test("daily quota errors are never retried while transient failures are", () => {
  const quota = classifyProviderError({
    status: 429,
    message: "You exceeded your daily quota.",
  });
  assert.equal(quota.retryable, false);
  assert.match(quota.message, /quota appears exhausted/i);

  const perDayQuota = classifyProviderError({
    status: 429,
    details: [{ quotaId: "GenerateRequestsPerDayPerProjectPerModel", retryDelay: "5s" }],
  });
  assert.equal(perDayQuota.retryable, false);

  const transient = classifyProviderError({ status: 503 });
  assert.equal(transient.retryable, true);

  const rateLimited = classifyProviderError({
    status: 429,
    message: "Rate limited",
    details: [{ retryDelay: "2s" }],
  });
  assert.equal(rateLimited.retryable, true);
  assert.equal(rateLimited.retryGuidanceMs, 2000);
});

test("calling the server startup helper twice does not open a duplicate listener", async () => {
  const started = startServer(0);
  assert.strictEqual(startServer(0), started);
  await new Promise((resolve) => (started.listening ? resolve() : started.once("listening", resolve)));
  await new Promise((resolve, reject) => started.close((error) => (error ? reject(error) : resolve())));
});
